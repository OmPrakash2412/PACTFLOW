import uuid
import datetime
import hashlib
from decimal import Decimal
from typing import List, Optional
from fastapi import APIRouter, HTTPException, status, Depends
from ..schemas.agreement import (
    AgreementGenerateRequest,
    AgreementResponse,
    AgreementAcceptanceRecord
)
from ..agents.pact_architect import pact_architect
from ..database.store import db_store
from .deps import get_current_user

router = APIRouter(prefix="/agreements", tags=["Agreements"])


@router.post("/generate", response_model=AgreementResponse)
async def generate_agreement(
    req: AgreementGenerateRequest,
    current_user: dict = Depends(get_current_user)
):
    project = db_store.projects.get(req.project_id)
    if not project:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Project not found.")

    budget = req.target_budget or project["budget"]
    requirements = req.requirements or project["description"]

    # Generate agreement using Pact Architect
    structure = await pact_architect.draft_agreement(
        project_title=project["title"],
        requirements=requirements,
        budget=budget,
        currency=project["currency"]
    )

    agreement_id = str(uuid.uuid4())
    now_iso = datetime.datetime.now(datetime.timezone.utc).isoformat()

    # Determine version
    existing_versions = [
        a["version"] for a in db_store.agreements.values() if a["project_id"] == req.project_id
    ]
    next_version = (max(existing_versions) + 1) if existing_versions else 1

    agreement_data = {
        "id": agreement_id,
        "project_id": req.project_id,
        "version": next_version,
        "title": structure.title,
        "scope_of_work": structure.scope_of_work,
        "budget_allocation": [b.model_dump() for b in structure.budget_allocation],
        "acceptance_criteria": structure.acceptance_criteria,
        "assumptions": structure.assumptions,
        "clarification_questions": structure.clarification_questions,
        "status": "pending_acceptance",
        "created_at": now_iso,
        "updated_at": now_iso
    }
    db_store.agreements[agreement_id] = agreement_data

    # Create the milestones generated by Pact Architect
    for ms in structure.suggested_milestones:
        m_id = str(uuid.uuid4())
        db_store.milestones[m_id] = {
            "id": m_id,
            "project_id": req.project_id,
            "agreement_id": agreement_id,
            "sequence_order": ms.sequence_order,
            "title": ms.title,
            "description": ms.description,
            "amount": ms.amount,
            "currency": project["currency"],
            "acceptance_criteria": ms.acceptance_criteria,
            "status": "pending",
            "created_at": now_iso,
            "updated_at": now_iso
        }

    # Record Trust Ledger event
    db_store.record_trust_event(
        project_id=req.project_id,
        event_type="AGREEMENT_GENERATED",
        actor_id=current_user["id"],
        entity_id=agreement_id,
        payload={"version": next_version, "title": structure.title}
    )

    return AgreementResponse(
        id=agreement_id,
        project_id=req.project_id,
        version=next_version,
        title=structure.title,
        scope_of_work=structure.scope_of_work,
        budget_allocation=[b.model_dump() for b in structure.budget_allocation],
        acceptance_criteria=structure.acceptance_criteria,
        assumptions=structure.assumptions,
        clarification_questions=structure.clarification_questions,
        status="pending_acceptance",
        created_at=now_iso,
        updated_at=now_iso,
        is_client_accepted=False,
        is_freelancer_accepted=False
    )


@router.get("/project/{project_id}", response_model=List[AgreementResponse])
async def get_agreements_by_project(project_id: str, current_user: dict = Depends(get_current_user)):
    agreements = [a for a in db_store.agreements.values() if a["project_id"] == project_id]
    agreements.sort(key=lambda x: x["version"], reverse=True)

    results = []
    for a in agreements:
        acceptances = [
            AgreementAcceptanceRecord(
                id=acc["id"],
                agreement_id=acc["agreement_id"],
                user_id=acc["user_id"],
                role=acc["role"],
                accepted_at=acc["accepted_at"],
                signature_hash=acc["signature_hash"]
            )
            for acc in db_store.agreement_acceptances.values()
            if acc["agreement_id"] == a["id"]
        ]

        is_client_accepted = any(acc.role == "client" for acc in acceptances)
        is_freelancer_accepted = any(acc.role == "freelancer" for acc in acceptances)

        results.append(AgreementResponse(
            id=a["id"],
            project_id=a["project_id"],
            version=a["version"],
            title=a["title"],
            scope_of_work=a["scope_of_work"],
            budget_allocation=a["budget_allocation"],
            acceptance_criteria=a["acceptance_criteria"],
            assumptions=a["assumptions"],
            clarification_questions=a["clarification_questions"],
            status=a["status"],
            created_at=a["created_at"],
            updated_at=a["updated_at"],
            acceptances=acceptances,
            is_client_accepted=is_client_accepted,
            is_freelancer_accepted=is_freelancer_accepted
        ))

    return results


@router.post("/{agreement_id}/accept", response_model=AgreementResponse)
async def accept_agreement(agreement_id: str, current_user: dict = Depends(get_current_user)):
    agreement = db_store.agreements.get(agreement_id)
    if not agreement:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Agreement not found.")

    user_id = current_user["id"]
    role = current_user.get("role", "client")

    # Check if already accepted by this user
    for acc in db_store.agreement_acceptances.values():
        if acc["agreement_id"] == agreement_id and acc["user_id"] == user_id:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail="You have already accepted this agreement version."
            )

    now_iso = datetime.datetime.now(datetime.timezone.utc).isoformat()
    # Compute digital cryptographic signature hash
    raw_sig = f"{agreement_id}:{user_id}:{role}:{now_iso}:{agreement['scope_of_work']}"
    sig_hash = hashlib.sha256(raw_sig.encode('utf-8')).hexdigest()

    acc_id = str(uuid.uuid4())
    db_store.agreement_acceptances[acc_id] = {
        "id": acc_id,
        "agreement_id": agreement_id,
        "user_id": user_id,
        "role": role,
        "accepted_at": now_iso,
        "signature_hash": sig_hash
    }

    # Record Trust Ledger event
    event_type = f"AGREEMENT_ACCEPTED_{role.upper()}"
    db_store.record_trust_event(
        project_id=agreement["project_id"],
        event_type=event_type,
        actor_id=user_id,
        entity_id=agreement_id,
        payload={"signature_hash": sig_hash, "version": agreement["version"]}
    )

    # Check if both client and freelancer have accepted
    all_acc = [
        acc for acc in db_store.agreement_acceptances.values() if acc["agreement_id"] == agreement_id
    ]
    has_client = any(a["role"] == "client" for a in all_acc)
    has_freelancer = any(a["role"] == "freelancer" for a in all_acc)

    if has_client and has_freelancer:
        agreement["status"] = "accepted"
        agreement["updated_at"] = now_iso
        # Update project status to active
        if agreement["project_id"] in db_store.projects:
            db_store.projects[agreement["project_id"]]["status"] = "active"

        # Record Trust event for dual-seal
        db_store.record_trust_event(
            project_id=agreement["project_id"],
            event_type="AGREEMENT_FULLY_EXECUTED",
            actor_id=user_id,
            entity_id=agreement_id,
            payload={"version": agreement["version"], "status": "accepted"}
        )

    # Build response
    acceptances = [
        AgreementAcceptanceRecord(
            id=acc["id"],
            agreement_id=acc["agreement_id"],
            user_id=acc["user_id"],
            role=acc["role"],
            accepted_at=acc["accepted_at"],
            signature_hash=acc["signature_hash"]
        )
        for acc in db_store.agreement_acceptances.values()
        if acc["agreement_id"] == agreement_id
    ]

    return AgreementResponse(
        id=agreement["id"],
        project_id=agreement["project_id"],
        version=agreement["version"],
        title=agreement["title"],
        scope_of_work=agreement["scope_of_work"],
        budget_allocation=agreement["budget_allocation"],
        acceptance_criteria=agreement["acceptance_criteria"],
        assumptions=agreement["assumptions"],
        clarification_questions=agreement["clarification_questions"],
        status=agreement["status"],
        created_at=agreement["created_at"],
        updated_at=agreement["updated_at"],
        acceptances=acceptances,
        is_client_accepted=any(acc.role == "client" for acc in acceptances),
        is_freelancer_accepted=any(acc.role == "freelancer" for acc in acceptances)
    )
